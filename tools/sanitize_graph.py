"""Second brain graph -> js/graph-data.js with structure only (no labels, no names).

Usage: python tools/sanitize_graph.py [--graph <path to graph.json>]
"""
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLUSTERS = ["Career and brand", "Events client", "Franchise client", "Photography client", "GHL standards", "Meta Ads", "Claude workflow"]
# graphify community -> generic cluster (communities 3, 4 and 5 are all the franchise client)
COMMUNITY = {0: 0, 1: 1, 2: 3, 3: 2, 4: 2, 5: 2, 6: 5}
# node id fragments that belong to a cross-client cluster instead of their community
BY_ID = {"claude": 6, "ghl_build_standards": 4}


def cluster_of(node):
    for frag, c in BY_ID.items():
        if frag in node["id"]:
            return c
    return COMMUNITY.get(node.get("community"), 6)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", default="G:/My Drive/AI/Claude-Workspace/graphify-out/graph.json")
    g = json.loads(Path(ap.parse_args().graph).read_text(encoding="utf-8"))
    index = {n["id"]: i for i, n in enumerate(g["nodes"])}
    nodes = [{"id": i, "c": cluster_of(n)} for i, n in enumerate(g["nodes"])]
    edges = [[index[e["source"]], index[e["target"]]] for e in g["links"]]
    text = "// Generated by tools/sanitize_graph.py: structure of Jose's second brain graph, no labels.\nexport default " + \
        json.dumps({"nodes": nodes, "edges": edges, "clusters": CLUSTERS}, separators=(",", ":")) + ";\n"

    # self-check: nothing from the original labels or the private names list leaks out
    low = text.lower()
    for n in g["nodes"]:
        for word in (n.get("label"), n.get("norm_label")):
            assert not word or word.lower() not in low, word
    names = ROOT / "tools" / "private-names.txt"
    for name in names.read_text().splitlines() if names.exists() else []:
        assert not name.strip() or name.strip().lower() not in low, name
    (ROOT / "js" / "graph-data.js").write_text(text)
    print(f"OK {len(nodes)} nodes, {len(edges)} edges, clusters used: {sorted({n['c'] for n in nodes})}")


if __name__ == "__main__":
    main()
